const serviceNames = ['Classic Cut', 'Beard Sculpt', 'Fade', 'Kids Cut', 'Hair Spa', 'D-Tan']
const serviceNamesInGujarati = serviceNames.map(name => [gu[name], name] as const)

type LocaleValue = { lang: Lang; setLang: (lang: Lang) => void; t: (text: string) => string }
const LocaleContext = createContext<LocaleValue>({ lang: 'en', setLang: () => undefined, t: text => text })
export function useLocale() { return useContext(LocaleContext) }

export function LocaleProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(() => localStorage.getItem(STORAGE_KEY) === 'gu' ? 'gu' : 'en')
  const setLang = (next: Lang) => { localStorage.setItem(STORAGE_KEY, next); setLangState(next) }
  const t = useMemo(() => (text: string) => {
    if (lang !== 'gu') return serviceNamesInGujarati.reduce((value, [source, translated]) => value.split(source).join(translated), text)
    if (gu[text]) return gu[text]
    return Object.entries(gu).filter(([source]) => source.length > 5 && !/[()]/.test(source)).sort(([a], [b]) => b.length - a.length).reduce((value, [source, translated]) => value.split(source).join(translated), text)
  }, [lang])
  useEffect(() => { document.documentElement.lang = lang === 'gu' ? 'gu' : 'en' }, [lang])
  return <LocaleContext.Provider value={{ lang, setLang, t }}>{children}</LocaleContext.Provider>
}

export function LanguageSwitcher() {
  const { lang, setLang } = useLocale()
  return <button type="button" className="lc-language-switch" onClick={() => setLang(lang === 'en' ? 'gu' : 'en')} aria-label={lang === 'en' ? 'Switch to Gujarati' : 'Switch to English'}>{lang === 'en' ? 'ગુજરાતી' : 'English'}</button>
}

/** Localizes visible text and accessible form labels throughout existing screens. */
export function LocaleTextBridge() {
  const { lang, t } = useLocale()
  const originals = useRef(new WeakMap<Text, string>()).current
  const rendered = useRef(new WeakMap<Text, string>()).current
  const attributeOriginals = useRef(new WeakMap<Element, Map<string, string>>()).current
  const attributeRendered = useRef(new WeakMap<Element, Map<string, string>>()).current
  useEffect(() => {
    const apply = (root: ParentNode) => {
      root.querySelectorAll<HTMLInputElement | HTMLTextAreaElement | HTMLButtonElement>('[placeholder],[title],[aria-label]').forEach(el => {
        const sourceValues = attributeOriginals.get(el) || new Map<string, string>()
        const renderedValues = attributeRendered.get(el) || new Map<string, string>()
        for (const attr of ['placeholder','title','aria-label'] as const) {
          const current = el.getAttribute(attr)
          if (!current) continue
          let source = sourceValues.get(attr)
          if (source === undefined || (renderedValues.has(attr) && current !== renderedValues.get(attr))) {
            source = current
            sourceValues.set(attr, source)
          }
          const next = lang === 'gu' ? t(source) : source
          if (current !== next) el.setAttribute(attr, next)
          renderedValues.set(attr, next)
        }
        attributeOriginals.set(el, sourceValues)
        attributeRendered.set(el, renderedValues)
      })
      const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT)
      let node: Node | null
      while ((node = walker.nextNode())) {
        const parent = node.parentElement
        if (!parent || parent.closest('script,style,textarea,input,[data-locale-skip]')) continue
        const textNode = node as Text
        const current = textNode.textContent || ''
        let source = originals.get(textNode)
        if (/[\u0A80-\u0AFF]/.test(current) && current !== rendered.get(textNode)) {
          // JoinQueue renders some Gujarati copy directly from its locale table.
          // Keep that React-provided text intact while retaining any English source.
          rendered.set(textNode, current)
          continue
        }
        if (source === undefined || (rendered.has(textNode) && current !== rendered.get(textNode))) {
          source = current
          originals.set(textNode, source)
        }
        const next = lang === 'gu' ? t(source) : source
        if (current !== next) {
          textNode.textContent = next
          rendered.set(textNode, next)
        } else rendered.set(textNode, current)
      }
    }
    apply(document.body)
    const observer = new MutationObserver(records => records.forEach(record => {
      if (record.type === 'characterData' && record.target.parentElement) apply(record.target.parentElement)
      if (record.type === 'attributes' && record.target instanceof Element) apply(record.target.parentElement || document.body)
      record.addedNodes.forEach(node => node instanceof HTMLElement ? apply(node) : node.parentElement && apply(node.parentElement))
    }))
    observer.observe(document.body, { childList: true, characterData: true, attributes: true, attributeFilter: ['placeholder', 'title', 'aria-label'], subtree: true })
    return () => observer.disconnect()
  }, [lang, t])
  return null
}
